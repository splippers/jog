#Requires -Version 5.1
<#
.SYNOPSIS
    Query FOG for the models in its inventory, fetch the latest vendor driver
    packs for those models, and publish extracted INF trees to the MIST Drivers
    share.

.DESCRIPTION
    The script reads the read-only MIST model API (mist-model-api.py) on the FOG
    appliance, selects the newest Dell and HP Windows driver pack for each
    distinct model, verifies the vendor SHA256, extracts the pack, and mirrors
    the extracted tree to:

        \\192.168.254.1\Drivers\<MODEL-SLUG>

    It also writes \\192.168.254.1\Drivers\manifest.json. The Windows
    provisioner reads that manifest (and falls back to the model slug) so a
    newly imaged client automatically installs the VMD base pack plus its
    model pack.

    The script runs on a Windows 11 workstation that can reach both the FOG
    appliance and the vendor download sites. The imaged client does not need
    internet access; it only needs the SMB share.

.PARAMETER ApiUrl
    MIST model API endpoint. Default http://192.168.254.1:8089/api/models.

.PARAMETER ApiToken
    Bearer token generated by mist-model-api-setup.sh. If omitted, the script
    reads ApiTokenFile.

.PARAMETER Model
    Optional manual model list. When supplied, the FOG API is not queried.

.PARAMETER OS
    Windows11 (default), Windows10, or Auto. Auto prefers Windows 11 and
    falls back to Windows 10 when the vendor has no Windows 11 pack.

.PARAMETER AllowWindows10Fallback
    With -OS Windows11, publish the latest Windows 10 pack when no Windows 11
    pack exists. Default true; the HP EliteBook 735 G6 is such a model.

.PARAMETER Minimal
    Drop the large video/audio category trees and Linux .so files before
    publishing. This keeps storage, chipset, network, input, security, and dock
    drivers. Display and audio drivers can be supplied by Windows Update.

.EXAMPLE
    .\Sync-FOGDriverPacks.ps1 -ApiTokenFile C:\ProgramData\MIST\model-api.token -WhatIf

.EXAMPLE
    .\Sync-FOGDriverPacks.ps1 -Model 'Latitude 3440','HP EliteBook 735 G6' -Force

.EXAMPLE
    .\Sync-FOGDriverPacks.ps1 -Minimal
#>
[CmdletBinding(SupportsShouldProcess = $true)]
param(
    [string]$ApiUrl = 'http://192.168.254.1:8089/api/models',
    [string]$ApiToken = '',
    [string]$ApiTokenFile = 'C:\ProgramData\MIST\model-api.token',
    [string[]]$Model = @(),
    [string]$Destination = '\\192.168.254.1\Drivers',
    [string]$UploadUser = 'driveradmin',
    [securestring]$UploadPassword,
    [string]$ReadUser = 'drivers',
    [securestring]$ReadPassword,
    [string]$WorkDir = (Join-Path $env:ProgramData 'MIST\driver-sync'),
    [ValidateSet('Windows11', 'Windows10', 'Auto')][string]$OS = 'Windows11',
    [bool]$AllowWindows10Fallback = $true,
    [ValidateSet('All', 'Dell', 'HP', 'Lenovo')][string]$Vendor = 'All',
    [switch]$NoUpload,
    [switch]$KeepDownloads,
    [switch]$Force,
    [switch]$Minimal,
    [switch]$PlanOnly
)

$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'JOGCommon.ps1')

$logDir = Join-Path $env:ProgramData 'MIST\logs'
New-Item -ItemType Directory -Force -Path $logDir | Out-Null
$script:JOGLogFile = Join-Path $logDir ('fog-driver-sync-{0}.log' -f (Get-Date -Format 'yyyyMMdd-HHmmss'))
New-Item -ItemType Directory -Force -Path $WorkDir | Out-Null
$script:PackCache = @{}
$script:Failures = @()

function Get-JOGXmlText {
    param($Node, [string]$XPath)
    if ($null -eq $Node) { return '' }
    $child = $Node.SelectSingleNode($XPath)
    if ($null -eq $child) { return '' }
    return ([string]$child.InnerText).Trim()
}

function Get-JOGNormalizedModel {
    param([string]$Value)
    if ([string]::IsNullOrWhiteSpace($Value)) { return '' }
    $v = $Value.ToLowerInvariant()
    # Remove vendor and generic chassis words, but keep model numbers such as
    # PC14250 intact: \bpc\b does not match the pc in PC14250.
    $v = $v -replace '\b(dell|inc\.?|hp|hewlett[- ]packard|lenovo|notebook| laptop| desktop| computer| corporation| company)\b', ' '
    $v = $v -replace '[^a-z0-9]+', ' '
    return ($v -replace '\s+', ' ').Trim()
}

function Test-JOGModelMatch {
    param([string]$FogModel, [string]$CatalogModel)
    $a = Get-JOGNormalizedModel $FogModel
    $b = Get-JOGNormalizedModel $CatalogModel
    if ([string]::IsNullOrWhiteSpace($a) -or [string]::IsNullOrWhiteSpace($b)) { return $false }
    if ($a -eq $b) { return $true }
    $at = @($a -split ' ')
    $bt = @($b -split ' ')
    $small = if ($at.Count -le $bt.Count) { $at } else { $bt }
    $large = if ($at.Count -le $bt.Count) { $bt } else { $at }
    if ($small.Count -lt 2) { return $false }
    foreach ($token in $small) {
        if ($large -notcontains $token) { return $false }
    }
    return $true
}

function Get-JOGApiToken {
    if (-not [string]::IsNullOrWhiteSpace($ApiToken)) { return $ApiToken }
    if (Test-Path $ApiTokenFile) {
        return (Get-Content -Path $ApiTokenFile -Raw).Trim()
    }
    $secure = Read-Host -AsSecureString 'MIST model API token'
    $bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure)
    try {
        return [Runtime.InteropServices.Marshal]::PtrToStringAuto($bstr)
    } finally {
        [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr)
    }
}

function Get-JOGFogModels {
    param([string]$Token)
    if ($Model.Count -gt 0) {
        return @($Model | ForEach-Object {
            [pscustomobject]@{
                manufacturer = ''
                model        = $_
                version      = ''
                product      = ''
                vendor       = if ($_ -match '(?i)^dell|latitude|precision|optiplex|vostro|inspiron|dell pro') { 'Dell' } elseif ($_ -match '(?i)^hp|hewlett|elitebook|probook|zbook') { 'HP' } elseif ($_ -match '(?i)^lenovo|thinkpad|thinkcentre') { 'Lenovo' } else { 'Unknown' }
                slug         = ConvertTo-JOGSlug $_
                count        = 0
                hosts        = @()
            }
        })
    }

    Write-JOGLog "Querying FOG model inventory: $ApiUrl"
    $headers = @{ Authorization = "Bearer $Token"; Accept = 'application/json' }
    try {
        $response = Invoke-RestMethod -Uri $ApiUrl -Headers $headers -Method Get -TimeoutSec 30
    } catch {
        throw "Cannot read the FOG model API at $ApiUrl : $($_.Exception.Message). Run mist-model-api-setup.sh --check on the appliance."
    }
    if (-not $response.ok) {
        throw "FOG model API returned an error: $($response.error)"
    }
    $models = @($response.models)
    if ($models.Count -eq 0) {
        throw "FOG returned no inventory models. Check that hosts have checked in and inventory is enabled."
    }
    return $models
}

function Get-JOGDownload {
    param(
        [string]$Url,
        [string]$OutFile,
        [string]$Sha256,
        [string]$Size
    )
    if ((Test-Path $OutFile) -and -not $Force) {
        Write-JOGLog "Using cached download: $OutFile"
        return
    }
    $part = "$OutFile.part"
    if (Test-Path $part) { Remove-Item -Path $part -Force -ErrorAction SilentlyContinue }
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $OutFile) | Out-Null
    Write-JOGLog "Downloading $Url"

    $curl = Get-Command curl.exe -ErrorAction SilentlyContinue
    if ($curl) {
        & $curl.Source -L --fail --retry 3 --connect-timeout 30 --output $part $Url
        if ($LASTEXITCODE -ne 0) {
            throw "curl.exe failed with exit $LASTEXITCODE for $Url"
        }
    } else {
        Invoke-WebRequest -Uri $Url -OutFile $part -UseBasicParsing
    }

    if (-not [string]::IsNullOrWhiteSpace($Size)) {
        $expected = [int64]$Size
        $actual = (Get-Item $part).Length
        if ($actual -ne $expected) {
            throw "Download size mismatch for $Url : expected $expected, got $actual"
        }
    }
    if (-not [string]::IsNullOrWhiteSpace($Sha256)) {
        $actualHash = (Get-FileHash -Path $part -Algorithm SHA256).Hash.ToLowerInvariant()
        if ($actualHash -ne $Sha256.ToLowerInvariant()) {
            throw "SHA256 mismatch for $Url : expected $Sha256, got $actualHash"
        }
    }
    Move-Item -Path $part -Destination $OutFile -Force
}

function Expand-JOGDriverPack {
    param(
        [string]$File,
        [string]$DestinationDir,
        [string]$PackVendor
    )
    if (Test-Path $DestinationDir) { Remove-Item -Path $DestinationDir -Recurse -Force }
    New-Item -ItemType Directory -Force -Path $DestinationDir | Out-Null

    $extension = [IO.Path]::GetExtension($File).ToLowerInvariant()
    if ($extension -eq '.cab') {
        & expand.exe $File -F:* $DestinationDir | Out-Null
        if ($LASTEXITCODE -ne 0) { throw "expand.exe failed with exit $LASTEXITCODE for $File" }
    } elseif ($PackVendor -eq 'Dell') {
        $p = Start-Process -FilePath $File -ArgumentList @('/s', "/e=$DestinationDir") -Wait -PassThru -WindowStyle Hidden
        if ($p.ExitCode -ne 0) { throw "Dell pack extraction failed with exit $($p.ExitCode)" }
    } elseif ($PackVendor -eq 'HP') {
        $p = Start-Process -FilePath $File -ArgumentList @('/s', '/e', '/f', $DestinationDir) -Wait -PassThru -WindowStyle Hidden
        if ($p.ExitCode -ne 0) {
            # Some SoftPaqs accept /e=<dir> rather than the /e /f form.
            $p = Start-Process -FilePath $File -ArgumentList @('/s', "/e=$DestinationDir") -Wait -PassThru -WindowStyle Hidden
        }
        if ($p.ExitCode -ne 0) { throw "HP pack extraction failed with exit $($p.ExitCode)" }
    } else {
        throw "Unsupported driver-pack type: $extension ($PackVendor)"
    }

    $infs = @(Get-ChildItem -Path $DestinationDir -Filter '*.inf' -Recurse -File -ErrorAction SilentlyContinue)
    if ($infs.Count -eq 0) {
        # A vendor EXE that is really a CAB, or an extractor that ignored the
        # requested directory, is recoverable here.
        & expand.exe $File -F:* $DestinationDir | Out-Null
        $infs = @(Get-ChildItem -Path $DestinationDir -Filter '*.inf' -Recurse -File -ErrorAction SilentlyContinue)
    }
    if ($infs.Count -eq 0) {
        throw "No .inf files found after extracting $File"
    }
    return $infs.Count
}

function Remove-JOGMinimalNoise {
    param([string]$Root)
    $rootItem = Get-Item -LiteralPath $Root
    $removed = 0
    $items = @(Get-ChildItem -LiteralPath $Root -Recurse -Force -ErrorAction SilentlyContinue |
        Sort-Object { $_.FullName.Length })
    foreach ($item in $items) {
        if (-not (Test-Path -LiteralPath $item.FullName)) { continue }
        $relative = $item.FullName.Substring($rootItem.FullName.Length).TrimStart('\')
        $depth = @($relative -split '[\\/]' | Where-Object { $_ }).Count
        if ($item.PSIsContainer -and $item.Name -in @('video', 'audio') -and $depth -le 4) {
            Remove-Item -LiteralPath $item.FullName -Recurse -Force -ErrorAction SilentlyContinue
            $removed++
        } elseif (-not $item.PSIsContainer -and $item.Extension -ieq '.so') {
            Remove-Item -LiteralPath $item.FullName -Force -ErrorAction SilentlyContinue
            $removed++
        }
    }
    $dirs = @(Get-ChildItem -LiteralPath $Root -Recurse -Force -Directory -ErrorAction SilentlyContinue |
        Sort-Object { $_.FullName.Length } -Descending)
    foreach ($dir in $dirs) {
        if (-not (Test-Path -LiteralPath $dir.FullName)) { continue }
        $children = @(Get-ChildItem -LiteralPath $dir.FullName -Force -ErrorAction SilentlyContinue)
        if ($children.Count -eq 0) {
            Remove-Item -LiteralPath $dir.FullName -Force -ErrorAction SilentlyContinue
        }
    }
    return $removed
}

function Get-JOGDellPacks {
    param([string]$CatalogXml)
    [xml]$xml = Get-Content -Path $CatalogXml -Raw
    $nodes = $xml.SelectNodes("//*[local-name()='DriverPackage']")
    $packs = @()
    foreach ($node in $nodes) {
        $format = [string]$node.GetAttribute('format')
        if ($format -notin @('exe', 'cab')) { continue }
        $osCodes = @()
        foreach ($osNode in $node.SelectNodes(".//*[local-name()='OperatingSystem']")) {
            $code = [string]$osNode.GetAttribute('osCode')
            $arch = [string]$osNode.GetAttribute('osArch')
            if ($arch -ne 'x64') { continue }
            if ($code -in @('Windows11', 'Windows10')) { $osCodes += $code }
        }
        if ($osCodes.Count -eq 0) { continue }

        $catalogModels = @()
        foreach ($modelNode in $node.SelectNodes(".//*[local-name()='Model']")) {
            $name = [string]$modelNode.GetAttribute('name')
            if (-not [string]::IsNullOrWhiteSpace($name)) { $catalogModels += $name }
        }
        if ($catalogModels.Count -eq 0) { continue }

        $hashNode = $node.SelectSingleNode(".//*[local-name()='Hash' and @algorithm='SHA256']")
        $sha = if ($hashNode) { $hashNode.InnerText.Trim().ToLowerInvariant() } else { '' }
        $relative = [string]$node.GetAttribute('path')
        if ([string]::IsNullOrWhiteSpace($relative) -or $relative.StartsWith('/') -or $relative -match '(^|/)\.\.?(/|$)') { continue }
        $date = [datetime]::MinValue
        [void][datetime]::TryParse([string]$node.GetAttribute('dateTime'), [ref]$date)
        $packs += [pscustomobject]@{
            Vendor       = 'Dell'
            CatalogModel = ($catalogModels -join '; ')
            CatalogModels = $catalogModels
            Date         = $date
            Version      = [string]$node.GetAttribute('dellVersion')
            Release      = [string]$node.GetAttribute('releaseID')
            Url          = "https://downloads.dell.com/$relative"
            Sha256       = $sha
            Size         = [string]$node.GetAttribute('size')
            Format       = $format
            OSCodes      = @($osCodes | Select-Object -Unique)
        }
    }
    return $packs
}

function Get-JOGHPPacks {
    param([string]$CatalogXml)
    [xml]$xml = Get-Content -Path $CatalogXml -Raw
    $softpaqs = @{}
    foreach ($sp in $xml.SelectNodes("//*[local-name()='SoftPaq']")) {
        $id = Get-JOGXmlText $sp "./*[local-name()='Id']"
        if ([string]::IsNullOrWhiteSpace($id)) { continue }
        $softpaqs[$id] = [pscustomobject]@{
            Url    = Get-JOGXmlText $sp "./*[local-name()='Url']"
            Sha256 = Get-JOGXmlText $sp "./*[local-name()='SHA256']"
            Size   = Get-JOGXmlText $sp "./*[local-name()='Size']"
            Date   = Get-JOGXmlText $sp "./*[local-name()='DateReleased']"
            Name   = Get-JOGXmlText $sp "./*[local-name()='Name']"
        }
    }
    $packs = @()
    foreach ($entry in $xml.SelectNodes("//*[local-name()='ProductOSDriverPack']")) {
        $systemName = Get-JOGXmlText $entry "./*[local-name()='SystemName']"
        $osName = Get-JOGXmlText $entry "./*[local-name()='OSName']"
        $softPaqId = Get-JOGXmlText $entry "./*[local-name()='SoftPaqId']"
        if ([string]::IsNullOrWhiteSpace($systemName) -or [string]::IsNullOrWhiteSpace($softPaqId)) { continue }
        $sp = $softpaqs[$softPaqId]
        if (-not $sp -or [string]::IsNullOrWhiteSpace($sp.Url)) { continue }

        if ($osName -notmatch 'Windows 1[01]') { continue }

        $date = [datetime]::MinValue
        [void][datetime]::TryParse($sp.Date, [Globalization.CultureInfo]::InvariantCulture, [Globalization.DateTimeStyles]::None, [ref]$date)
        $osCode = ''
        if ($osName -match 'Windows 11') { $osCode = 'Windows11' }
        elseif ($osName -match 'Windows 10') { $osCode = 'Windows10' }
        $packs += [pscustomobject]@{
            Vendor       = 'HP'
            CatalogModel = $systemName
            CatalogModels = @($systemName)
            Date         = $date
            Version      = ''
            Release      = $softPaqId
            Url          = $sp.Url
            Sha256       = ([string]$sp.Sha256).Trim().ToLowerInvariant()
            Size         = $sp.Size
            Format       = 'exe'
            OSName       = $osName
            OSCodes      = @($osCode)
        }
    }
    return $packs
}

function Select-JOGPack {
    param($FogModel, [object[]]$Packs, [string]$TargetOS)
    $matches = @($Packs | Where-Object {
        if ($TargetOS -and (@($_.OSCodes) -notcontains $TargetOS)) { return $false }
        foreach ($catalogModel in $_.CatalogModels) {
            if (Test-JOGModelMatch -FogModel $FogModel.model -CatalogModel $catalogModel) { return $true }
        }
        return $false
    })
    if ($matches.Count -eq 0) { return $null }
    return ($matches | Sort-Object -Property Date, Release -Descending | Select-Object -First 1)
}

function Get-JOGPackForModel {
    param($FogModel, [object[]]$DellPacks, [object[]]$HPPacks, [string]$TargetOS)
    $modelVendor = [string]$FogModel.vendor
    $candidates = @()
    if ($modelVendor -eq 'Dell' -and $DellPacks) { $candidates = $DellPacks }
    elseif ($modelVendor -eq 'HP' -and $HPPacks) { $candidates = $HPPacks }
    elseif ($Vendor -eq 'All') { $candidates = @($DellPacks) + @($HPPacks) }
    else { return $null }
    return Select-JOGPack -FogModel $FogModel -Packs $candidates -TargetOS $TargetOS
}

function Get-JOGPackForModelWithFallback {
    param($FogModel, [object[]]$DellPacks, [object[]]$HPPacks)
    $targets = if ($OS -eq 'Auto') { @('Windows11', 'Windows10') } else { @($OS) }
    if ($OS -eq 'Windows11' -and $AllowWindows10Fallback) { $targets = @('Windows11', 'Windows10') }
    foreach ($target in $targets) {
        $pack = Get-JOGPackForModel -FogModel $FogModel -DellPacks $DellPacks -HPPacks $HPPacks -TargetOS $target
        if ($pack) {
            if ($target -ne $OS -and $OS -ne 'Auto') {
                Write-JOGLog "No $OS pack for $($FogModel.model); using $target fallback." -Level WARN
            }
            return $pack
        }
    }
    return $null
}

function Get-JOGManifestEntry {
    param($FogModel, $Pack, [string]$Folder)
    [pscustomobject]@{
        model     = [string]$FogModel.model
        vendor    = [string]$Pack.Vendor
        folder    = $Folder
        pack      = [string]$Pack.Release
        version   = [string]$Pack.Version
        date      = $Pack.Date.ToString('o')
        url       = [string]$Pack.Url
        sha256    = [string]$Pack.Sha256
        aliases   = @($FogModel.model, ("{0} {1}" -f $FogModel.manufacturer, $FogModel.model) | Where-Object { -not [string]::IsNullOrWhiteSpace($_) } | Select-Object -Unique)
    }
}

# --- credentials -----------------------------------------------------------

if (-not $NoUpload -and -not $UploadPassword) {
    $UploadPassword = Read-Host -AsSecureString "Password for $UploadUser at $Destination"
}
if ($ReadPassword) {
    $bstrRead = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($ReadPassword)
    try { $plainRead = [Runtime.InteropServices.Marshal]::PtrToStringAuto($bstrRead) } finally { [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstrRead) }
}

# --- catalog download ------------------------------------------------------

$catalogDir = Join-Path $WorkDir 'catalog'
New-Item -ItemType Directory -Force -Path $catalogDir | Out-Null
$dellPacks = @()
$hpPacks = @()

if ($Vendor -in @('All', 'Dell')) {
    $dellCab = Join-Path $catalogDir 'DriverPackCatalog.cab'
    Get-JOGDownload -Url 'https://downloads.dell.com/catalog/DriverPackCatalog.cab' -OutFile $dellCab
    $dellXmlDir = Join-Path $catalogDir 'dell'
    if (Test-Path $dellXmlDir) { Remove-Item -Path $dellXmlDir -Recurse -Force }
    New-Item -ItemType Directory -Force -Path $dellXmlDir | Out-Null
    & expand.exe $dellCab -F:* $dellXmlDir | Out-Null
    if ($LASTEXITCODE -ne 0) { throw "Could not extract the Dell driver catalog (exit $LASTEXITCODE)" }
    $dellXml = Get-ChildItem -Path $dellXmlDir -Filter 'DriverPackCatalog.xml' -Recurse -File | Select-Object -First 1
    if (-not $dellXml) { throw "Dell catalog did not contain DriverPackCatalog.xml" }
    $dellPacks = @(Get-JOGDellPacks -CatalogXml $dellXml.FullName)
    Write-JOGLog "Dell catalog: $($dellPacks.Count) candidate pack(s) across Windows 10/11"
}

if ($Vendor -in @('All', 'HP')) {
    $hpCab = Join-Path $catalogDir 'HPClientDriverPackCatalog.cab'
    Get-JOGDownload -Url 'https://hpia.hpcloud.hp.com/downloads/driverpackcatalog/HPClientDriverPackCatalog.cab' -OutFile $hpCab
    $hpXmlDir = Join-Path $catalogDir 'hp'
    if (Test-Path $hpXmlDir) { Remove-Item -Path $hpXmlDir -Recurse -Force }
    New-Item -ItemType Directory -Force -Path $hpXmlDir | Out-Null
    & expand.exe $hpCab -F:* $hpXmlDir | Out-Null
    if ($LASTEXITCODE -ne 0) { throw "Could not extract the HP driver catalog (exit $LASTEXITCODE)" }
    $hpXml = Get-ChildItem -Path $hpXmlDir -Filter 'HPClientDriverPackCatalog.xml' -Recurse -File | Select-Object -First 1
    if (-not $hpXml) { throw "HP catalog did not contain HPClientDriverPackCatalog.xml" }
    $hpPacks = @(Get-JOGHPPacks -CatalogXml $hpXml.FullName)
    Write-JOGLog "HP catalog: $($hpPacks.Count) candidate pack(s) across Windows 10/11"
}

# --- resolve FOG models ----------------------------------------------------

$token = ''
if ($Model.Count -eq 0) { $token = Get-JOGApiToken }
$fogModels = @(Get-JOGFogModels -Token $token)
$fogModels = @($fogModels | Where-Object {
    $Vendor -eq 'All' -or $_.vendor -eq $Vendor
})
if ($fogModels.Count -eq 0) { throw "No FOG models match vendor filter '$Vendor'" }

Write-JOGLog "FOG models: $($fogModels.Count)"
foreach ($m in $fogModels) {
    Write-JOGLog ("  {0} / {1} ({2} host(s))" -f $m.vendor, $m.model, $m.count)
}

$resolved = @()
foreach ($m in $fogModels) {
    $pack = Get-JOGPackForModelWithFallback -FogModel $m -DellPacks $dellPacks -HPPacks $hpPacks
    if (-not $pack) {
        $script:Failures += "No driver pack for $($m.vendor) $($m.model)"
        Write-JOGLog "No driver pack for $($m.vendor) $($m.model)" -Level WARN
        continue
    }
    $folder = ConvertTo-JOGSlug $m.model
    Write-JOGLog ("Matched {0} -> {1} {2} ({3})" -f $m.model, $pack.Vendor, $pack.Release, $pack.Date.ToString('yyyy-MM-dd'))
    $resolved += [pscustomobject]@{ Fog = $m; Pack = $pack; Folder = $folder }
}

if ($resolved.Count -eq 0) { throw "No models could be matched to a vendor driver pack" }

if ($PlanOnly -or $WhatIfPreference) {
    foreach ($item in $resolved) {
        Write-JOGLog ("Plan: {0} -> {1} {2} {3} -> {4}" -f $item.Fog.model, $item.Pack.Vendor, $item.Pack.Release, $item.Pack.Date.ToString('yyyy-MM-dd'), $item.Folder)
    }
    Write-JOGLog "Plan only; no packs downloaded or published."
    return
}

# --- download, extract, publish -------------------------------------------

$manifestEntries = @()
$uploadMapped = $false
$plainUpload = ''
if (-not $NoUpload) {
    $bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($UploadPassword)
    try { $plainUpload = [Runtime.InteropServices.Marshal]::PtrToStringAuto($bstr) } finally { [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr) }
    $uploadMapped = New-JOGSmbMapping -RemotePath $Destination -UserName $UploadUser -Password $plainUpload
    if (-not $uploadMapped) { throw "Could not map $Destination as $UploadUser" }
}

try {
    foreach ($item in $resolved) {
        $m = $item.Fog
        $pack = $item.Pack
        $folder = $item.Folder
        $target = Join-Path $Destination $folder
        try {
            if ($WhatIfPreference) {
                Write-JOGLog "WhatIf: would publish $($pack.Vendor) $($pack.Release) to $target"
                $manifestEntries += Get-JOGManifestEntry -FogModel $m -Pack $pack -Folder $folder
                continue
            }

            $cacheKey = $pack.Url
            if (-not $script:PackCache.ContainsKey($cacheKey)) {
                $extension = if ($pack.Format -eq 'cab') { '.cab' } else { '.exe' }
                $download = Join-Path $WorkDir ('downloads\{0}\{1}{2}' -f $pack.Vendor, (ConvertTo-JOGSlug $pack.Release), $extension)
                Get-JOGDownload -Url $pack.Url -OutFile $download -Sha256 $pack.Sha256 -Size $pack.Size
                $extractDir = Join-Path $WorkDir ('extract\{0}\{1}' -f $pack.Vendor, (ConvertTo-JOGSlug $pack.Release))
                $infCount = Expand-JOGDriverPack -File $download -DestinationDir $extractDir -PackVendor $pack.Vendor
                $script:PackCache[$cacheKey] = [pscustomobject]@{ Download = $download; Extract = $extractDir; InfCount = $infCount }
                Write-JOGLog "Extracted $infCount INF file(s) from $($pack.Release)"
            } else {
                Write-JOGLog "Reusing extracted pack for $($pack.Release)"
            }

            $cache = $script:PackCache[$cacheKey]
            $staging = Join-Path $WorkDir ('publish\{0}' -f $folder)
            if (Test-Path $staging) { Remove-Item -Path $staging -Recurse -Force }
            New-Item -ItemType Directory -Force -Path $staging | Out-Null
            Copy-Item -Path (Join-Path $cache.Extract '*') -Destination $staging -Recurse -Force
            if ($Minimal) {
                $removed = Remove-JOGMinimalNoise -Root $staging
                Write-JOGLog "Minimal profile: removed $removed video/audio/.so item(s) from $folder"
            }

            $packInfo = Get-JOGManifestEntry -FogModel $m -Pack $pack -Folder $folder
            $packInfo | ConvertTo-Json -Depth 6 | Set-Content -Path (Join-Path $staging 'pack.json') -Encoding UTF8
            $manifestEntries += $packInfo

            if ($NoUpload) {
                Write-JOGLog "NoUpload: staged $folder at $staging"
                continue
            }
            if ($PSCmdlet.ShouldProcess($target, "publish $($pack.Vendor) $($pack.Release)")) {
                Write-JOGLog "Publishing $folder to $target"
                $rc = Invoke-JOGProcess -FilePath 'robocopy.exe' -ArgumentList @(
                    $staging, $target, '/MIR', '/R:2', '/W:2', '/NP', '/NFL', '/NDL',
                    "/LOG:$($script:JOGLogFile).robocopy"
                )
                if ($rc.ExitCode -ge 8) { throw "robocopy failed (exit $($rc.ExitCode)) for $target" }
                Write-JOGLog "Published $folder (robocopy exit $($rc.ExitCode))"
            }
        } catch {
            $script:Failures += "$($m.model): $($_.Exception.Message)"
            Write-JOGLog "Failed for $($m.model): $($_.Exception.Message)" -Level ERROR
        }
    }

    # Update the manifest on the share so the provisioner can resolve aliases.
    if (-not $WhatIfPreference) {
        $manifestPath = Join-Path $WorkDir 'manifest.json'
        $existing = @()
        if (-not $NoUpload -and (Test-Path (Join-Path $Destination 'manifest.json'))) {
            try {
                $old = Get-Content -Path (Join-Path $Destination 'manifest.json') -Raw | ConvertFrom-Json
                if ($old.models) { $existing = @($old.models) }
            } catch {
                Write-JOGLog "Existing manifest is unreadable; replacing it." -Level WARN
            }
        }
        $byFolder = @{}
        foreach ($entry in $existing) {
            if ($entry.folder) { $byFolder[[string]$entry.folder] = $entry }
        }
        foreach ($entry in $manifestEntries) {
            $byFolder[[string]$entry.folder] = $entry
        }
        $manifest = [pscustomobject]@{
            schema    = 1
            generated = (Get-Date).ToString('o')
            models    = @($byFolder.Values | Sort-Object folder)
        }
        $manifest | ConvertTo-Json -Depth 8 | Set-Content -Path $manifestPath -Encoding UTF8
        if (-not $NoUpload) {
            Copy-Item -Path $manifestPath -Destination (Join-Path $Destination 'manifest.json') -Force
            Write-JOGLog "Updated $Destination\manifest.json"
        } else {
            Write-JOGLog "NoUpload: manifest at $manifestPath"
        }
    }
} finally {
    if ($uploadMapped) { Remove-JOGSmbMapping -RemotePath $Destination }
    if (-not $KeepDownloads) {
        # Keep the catalog and manifest for diagnosis; drop the multi-gigabyte
        # pack downloads unless the caller asked to keep them.
        foreach ($name in @('downloads', 'extract', 'publish')) {
            $path = Join-Path $WorkDir $name
            if (Test-Path $path) { Remove-Item -Path $path -Recurse -Force -ErrorAction SilentlyContinue }
        }
    }
}

if ($script:Failures.Count -gt 0) {
    Write-JOGLog "Completed with $($script:Failures.Count) failure(s):" -Level ERROR
    foreach ($failure in $script:Failures) { Write-JOGLog "  $failure" -Level ERROR }
    exit 1
}

Write-JOGLog "Done. $($resolved.Count) model pack(s) published. Log: $($script:JOGLogFile)"
