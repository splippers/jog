#!/bin/bash
set -euo pipefail
exec 2>>/tmp/mist_error.log

# mist-driver-share.sh — idempotent Samba [Drivers] share for the Brume corporate pipeline.
#
#   sudo mist-driver-share.sh --check     # report only, no changes
#   sudo mist-driver-share.sh --apply     # create groups/users/path/share, reload Samba
#   sudo mist-driver-share.sh --rotate    # generate new passwords and update Samba
#
# Read account:  drivers      (read-only; used by the Windows provisioner)
# Write account: driveradmin  (upload; used by Sync-JOGDrivers.ps1)
#
# Settings come from /etc/mist/mist.env when present:
#   JOG_DRIVER_SHARE_NAME, JOG_DRIVER_SHARE_PATH, JOG_DRIVER_READ_USER,
#   JOG_DRIVER_WRITE_USER, JOG_DRIVER_ALLOW_GUEST
#
# The generated credentials are written to /etc/mist/driver-share.env (0600).
# They are never printed by --check.

log()  { echo "[mist-driver-share] $*"; }
warn() { echo "[mist-driver-share] WARN: $*" >&2; }
die()  { echo "[mist-driver-share] ERROR: $*" >&2; exit 1; }

MODE="--check"
ROTATE=0
for arg in "$@"; do
  case "$arg" in
    --check)  MODE="--check" ;;
    --apply)  MODE="--apply" ;;
    --rotate) MODE="--rotate" ;;
    -h|--help)
      sed -n '2,30p' "$0" | sed 's/^# \{0,1\}//'
      exit 0
      ;;
    *) die "unknown argument: $arg" ;;
  esac
done

if [[ -f /etc/mist/mist.env ]]; then
  set -a
  # shellcheck disable=SC1091
  source /etc/mist/mist.env
  set +a
fi

SHARE_NAME="${Brume_DRIVER_SHARE_NAME:-${JOG_DRIVER_SHARE_NAME:-Drivers}}"
SHARE_PATH="${Brume_DRIVER_SHARE_PATH:-${JOG_DRIVER_SHARE_PATH:-/srv/mist/drivers}}"
READ_USER="${Brume_DRIVER_READ_USER:-${JOG_DRIVER_READ_USER:-drivers}}"
WRITE_USER="${Brume_DRIVER_WRITE_USER:-${JOG_DRIVER_WRITE_USER:-driveradmin}}"
ALLOW_GUEST="${Brume_DRIVER_ALLOW_GUEST:-${JOG_DRIVER_ALLOW_GUEST:-0}}"

SHARE_USER="${Brume_DRIVER_SHARE_USER:-${JOG_DRIVER_SHARE_USER:-jogshare}}"
READ_GROUP="${Brume_DRIVER_READ_GROUP:-${JOG_DRIVER_READ_GROUP:-jogdrivers}}"
WRITE_GROUP="${Brume_DRIVER_WRITE_GROUP:-${JOG_DRIVER_WRITE_GROUP:-jogdriveradmin}}"

ENV_FILE="/etc/mist/driver-share.env"
SMB_INCLUDE="/etc/samba/mist-drivers.conf"
SMB_CONF="/etc/samba/smb.conf"
MARKER="# Managed by mist-driver-share.sh"

need_root() {
  [[ "$(id -u)" -eq 0 ]] || die "run as root: sudo $0 $MODE"
}

samba_installed() {
  command -v smbd >/dev/null 2>&1
}

inline_share_present() {
  [[ -f "$SMB_CONF" ]] && grep -qE "^[[:space:]]*\[${SHARE_NAME}\][[:space:]]*$" "$SMB_CONF"
}

include_present() {
  [[ -f "$SMB_CONF" ]] && grep -qF "include = ${SMB_INCLUDE}" "$SMB_CONF"
}

load_passwords() {
  if [[ -f "$ENV_FILE" ]]; then
    # shellcheck disable=SC1090
    source "$ENV_FILE"
  fi
  READ_PASS="${JOG_DRIVER_READ_PASSWORD:-}"
  WRITE_PASS="${JOG_DRIVER_WRITE_PASSWORD:-}"
}

generate_password() {
  openssl rand -hex 16
}

save_passwords() {
  umask 077
  install -d -m 0755 /etc/mist
  cat > "$ENV_FILE" <<EOF
# Generated by mist-driver-share.sh — do not commit.
JOG_DRIVER_SHARE_NAME='${SHARE_NAME}'
JOG_DRIVER_SHARE_PATH='${SHARE_PATH}'
JOG_DRIVER_READ_USER='${READ_USER}'
JOG_DRIVER_WRITE_USER='${WRITE_USER}'
JOG_DRIVER_READ_PASSWORD='${READ_PASS}'
JOG_DRIVER_WRITE_PASSWORD='${WRITE_PASS}'
EOF
  chmod 0600 "$ENV_FILE"
  chown root:root "$ENV_FILE" 2>/dev/null || true
}

ensure_group() {
  local group="$1"
  getent group "$group" >/dev/null 2>&1 || groupadd --system "$group"
}

ensure_user() {
  local user="$1" group="$2"
  if ! id -u "$user" >/dev/null 2>&1; then
    useradd --system --no-create-home --shell /usr/sbin/nologin --gid "$group" "$user"
  fi
  usermod -aG "$group" "$user"
}

set_samba_password() {
  local user="$1" pass="$2"
  if ! id -u "$user" >/dev/null 2>&1; then
    useradd --system --no-create-home --shell /usr/sbin/nologin "$user"
  fi
  printf '%s\n%s\n' "$pass" "$pass" | smbpasswd -s -a "$user" >/dev/null
  smbpasswd -e "$user" >/dev/null
}

write_include() {
  local guest_line="guest ok = no"
  local valid_line="valid users = @${READ_GROUP}, @${WRITE_GROUP}"
  if [[ "$ALLOW_GUEST" == "1" ]]; then
    guest_line="guest ok = yes"
    valid_line=""
  fi

  cat > "$SMB_INCLUDE" <<EOF
${MARKER}
# Read-only for clients, write for the upload account.
[${SHARE_NAME}]
   comment = Brume corporate driver repository
   path = ${SHARE_PATH}
   browseable = yes
   read only = yes
   ${guest_line}
$( [[ -n "$valid_line" ]] && echo "   ${valid_line}" )
   write list = @${WRITE_GROUP}
   force user = ${SHARE_USER}
   force group = ${READ_GROUP}
   create mask = 0664
   directory mask = 2775
   # No guest write, no symlink escape.
   follow symlinks = yes
   wide links = no
EOF
  chmod 0644 "$SMB_INCLUDE"
}

ensure_include() {
  if include_present; then
    log "include already present in ${SMB_CONF}"
    return 0
  fi
  if inline_share_present; then
    warn "an inline [${SHARE_NAME}] section already exists in ${SMB_CONF}."
    warn "Leaving it untouched. Point JOG_DRIVER_SHARE_PATH at that path, or remove the inline"
    warn "section and re-run --apply to use the managed include."
    return 1
  fi
  local backup="${SMB_CONF}.bak-mist-$(date +%Y%m%d-%H%M%S)"
  cp -a "$SMB_CONF" "$backup"
  printf '\n%s\ninclude = %s\n' "$MARKER" "$SMB_INCLUDE" >> "$SMB_CONF"
  log "added include to ${SMB_CONF} (backup: ${backup})"
}

ensure_path() {
  install -d -m 2775 -o "$SHARE_USER" -g "$READ_GROUP" "$SHARE_PATH"
  chmod 2775 "$SHARE_PATH"
  # Do not recursively chown an existing repository; just make sure the share
  # owner can traverse it and the group can read new content.
  chown "$SHARE_USER:$READ_GROUP" "$SHARE_PATH"
  log "share path: ${SHARE_PATH} (${SHARE_USER}:${READ_GROUP}, 2775)"
}

reload_samba() {
  testparm -s >/dev/null 2>&1 || die "testparm rejected the Samba configuration; not reloading"
  if systemctl list-unit-files smbd.service >/dev/null 2>&1; then
    systemctl reload smbd 2>/dev/null || systemctl restart smbd
  elif systemctl list-unit-files smb.service >/dev/null 2>&1; then
    systemctl reload smb 2>/dev/null || systemctl restart smb
  else
    warn "no smbd/smb systemd unit found; start Samba manually"
  fi
}

test_share() {
  if ! command -v smbclient >/dev/null 2>&1; then
    warn "smbclient not installed; skipping live share test"
    return 0
  fi
  local unc="//127.0.0.1/${SHARE_NAME}"
  if smbclient "$unc" -U "${READ_USER}%${READ_PASS}" -c 'ls' >/dev/null 2>&1; then
    log "read test: ${READ_USER} can list ${unc}"
  else
    warn "read test failed for ${READ_USER} on ${unc}"
    return 1
  fi
  if smbclient "$unc" -U "${WRITE_USER}%${WRITE_PASS}" -c 'mkdir .mist-write-test; rmdir .mist-write-test' >/dev/null 2>&1; then
    log "write test: ${WRITE_USER} can write to ${unc}"
  else
    warn "write test failed for ${WRITE_USER} on ${unc}"
    return 1
  fi
}

show_summary() {
  cat <<EOF
[mist-driver-share] configuration
  share name : ${SHARE_NAME}
  path       : ${SHARE_PATH}
  read user  : ${READ_USER}  (group ${READ_GROUP})
  write user : ${WRITE_USER} (group ${WRITE_GROUP})
  guest      : ${ALLOW_GUEST}
  include    : ${SMB_INCLUDE}
  credentials: ${ENV_FILE} (0600)
  UNC        : \\\\${Brume_IMAGING_IP:-${JOG_IMAGING_IP:-10.99.0.1}}\\${SHARE_NAME}
EOF
}

# --- check -----------------------------------------------------------------

if [[ "$MODE" == "--check" ]]; then
  rc=0
  samba_installed || { warn "Samba is not installed (apt install samba smbclient)"; rc=1; }
  [[ -f "$SMB_CONF" ]] || { warn "missing ${SMB_CONF}"; rc=1; }
  [[ -d "$SHARE_PATH" ]] || { warn "share path does not exist: ${SHARE_PATH}"; rc=1; }
  include_present || { warn "managed include not present in ${SMB_CONF}"; rc=1; }
  inline_share_present && warn "inline [${SHARE_NAME}] section also exists; resolve the duplicate"
  [[ -f "$ENV_FILE" ]] || { warn "credentials not generated yet: ${ENV_FILE}"; rc=1; }
  id -u "$READ_USER" >/dev/null 2>&1 || { warn "read user missing: ${READ_USER}"; rc=1; }
  id -u "$WRITE_USER" >/dev/null 2>&1 || { warn "write user missing: ${WRITE_USER}"; rc=1; }
  id -u "$SHARE_USER" >/dev/null 2>&1 || { warn "share user missing: ${SHARE_USER}"; rc=1; }
  command -v testparm >/dev/null 2>&1 && { testparm -s >/dev/null 2>&1 || { warn "testparm rejected the config"; rc=1; }; }
  show_summary
  [[ "$rc" -eq 0 ]] && log "check passed" || log "check found issues; run --apply"
  exit "$rc"
fi

# --- apply / rotate --------------------------------------------------------

need_root
samba_installed || die "Samba is not installed. Run: apt-get install -y samba smbclient"

load_passwords
if [[ "$MODE" == "--rotate" ]] || [[ -z "$READ_PASS" ]] || [[ -z "$WRITE_PASS" ]]; then
  READ_PASS="$(generate_password)"
  WRITE_PASS="$(generate_password)"
  log "generated new credentials"
fi

ensure_group "$READ_GROUP"
ensure_group "$WRITE_GROUP"
ensure_user "$SHARE_USER" "$READ_GROUP"
usermod -aG "$WRITE_GROUP" "$SHARE_USER"
ensure_user "$READ_USER" "$READ_GROUP"
ensure_user "$WRITE_USER" "$WRITE_GROUP"

set_samba_password "$READ_USER" "$READ_PASS"
set_samba_password "$WRITE_USER" "$WRITE_PASS"

ensure_path
write_include
save_passwords

if ! ensure_include; then
  if [[ "$MODE" == "--rotate" ]]; then
    warn "inline share in use; credentials rotated, managed include not added."
    show_summary
    exit 0
  fi
  warn "share include was not added; the inline section is still in use."
  warn "Credentials are in ${ENV_FILE}; update the inline share manually if needed."
  exit 1
fi

reload_samba
test_share || true
show_summary
log "done. Upload drivers with Sync-JOGDrivers.ps1 as ${WRITE_USER}."
