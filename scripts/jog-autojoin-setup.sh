#!/bin/bash
set -euo pipefail
exec 2>>/tmp/jog_error.log

# jog-autojoin-setup.sh — install the JOS multicast auto-join endpoint.
#
#   sudo jog-autojoin-setup.sh --apply
#   sudo jog-autojoin-setup.sh --check
#
# The endpoint lives beside FOG's own service endpoints:
#   /var/www/html/fog/service/jog-autojoin.php
#
# It is called by JOS's default PXE entry before the FOG host-key handshake.
# If a multicast session is still in its join window, it creates the same
# per-host multicast task association as the "Join Multicast Session" menu.
# If no session is waiting, JOS falls back to the local disk. No FOG login is
# needed on the client, and no FOG credential is stored in the initrd.

log()  { echo "[jog-autojoin-setup] $*"; }
warn() { echo "[jog-autojoin-setup] WARN: $*" >&2; }
die()  { echo "[jog-autojoin-setup] ERROR: $*" >&2; exit 1; }

MODE="--check"
for arg in "$@"; do
  case "$arg" in
    --apply) MODE="--apply" ;;
    --check) MODE="--check" ;;
    -h|--help) sed -n '2,24p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) die "unknown argument: $arg" ;;
  esac
done

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="${JOG_AUTOJOIN_SRC:-$ROOT/scripts/jog-autojoin.php}"
[[ -f "$SRC" ]] || SRC=/usr/local/share/jog/scripts/jog-autojoin.php
WEBROOT="${JOG_FOG_WEBROOT:-/var/www/html/fog}"
[[ -d "$WEBROOT/service" ]] || WEBROOT=/var/www/fog
TARGET="$WEBROOT/service/jog-autojoin.php"
ENV_FILE=/etc/jog/jog.env
AUTOJOIN_ENV=/etc/jog/autojoin.env

check() {
  local rc=0
  if [[ -f "$TARGET" ]]; then log "ok    endpoint installed: $TARGET"; else warn "FAIL  endpoint missing: $TARGET (run --apply)"; rc=1; fi
  if [[ -f "$TARGET" ]] && php -l "$TARGET" >/dev/null 2>&1; then log "ok    endpoint parses"; else warn "FAIL  endpoint does not parse"; rc=1; fi
  if [[ -r "$AUTOJOIN_ENV" ]] && grep -q '^JOG_AUTOJOIN_ALLOW_NET=' "$AUTOJOIN_ENV"; then
    log "ok    $(grep '^JOG_AUTOJOIN_ALLOW_NET=' "$AUTOJOIN_ENV")"
  elif [[ -r "$ENV_FILE" ]] && grep -q '^JOG_AUTOJOIN_ALLOW_NET=' "$ENV_FILE"; then
    log "ok    $(grep '^JOG_AUTOJOIN_ALLOW_NET=' "$ENV_FILE")"
  else
    warn "WARN  JOG_AUTOJOIN_ALLOW_NET not set; endpoint defaults to the imaging /24"
  fi
  if command -v curl >/dev/null 2>&1; then
    local code body
    body="$(curl -sS -w $'\n%{http_code}' --max-time 5 \
      -X POST --data 'probe=1' \
      "http://127.0.0.1/fog/service/jog-autojoin.php" 2>/dev/null || true)"
    code="${body##*$'\n'}"
    body="${body%$'\n'*}"
    # The endpoint terminates its line with \n and curl adds another before
    # the status, so the extracted body can still carry a trailing newline.
    body="$(printf '%s' "$body" | tr -d '\r\n')"
    if [[ "$code" == "200" && "$body" == "OK ALIVE" ]]; then
      log "ok    endpoint is reachable (probe: $body)"
    else
      case "$code" in
        404) warn "FAIL  endpoint returns 404 (check $WEBROOT/service)" ;;
        403) warn "FAIL  endpoint refused localhost probe (HTTP 403); check JOG_AUTOJOIN_ALLOW_NET" ;;
        *)   warn "WARN  endpoint probe returned HTTP ${code:-none}: ${body:-empty}" ;;
      esac
      rc=1
    fi
  else
    warn "WARN  curl not installed; skipping endpoint reachability check"
  fi
  return "$rc"
}

if [[ "$MODE" == "--check" ]]; then
  check
  exit $?
fi

[[ "$(id -u)" -eq 0 ]] || die "run as root: sudo $0 --apply"
[[ -f "$SRC" ]] || die "source endpoint not found: $SRC"
[[ -d "$WEBROOT/service" ]] || die "FOG service directory not found under $WEBROOT (is FOG installed?)"
php -l "$SRC" >/dev/null 2>&1 || die "source endpoint does not parse: $SRC"

install -m 0644 "$SRC" "$TARGET"
chown www-data:www-data "$TARGET" 2>/dev/null || true

# Keep the endpoint reachable only from the imaging network. JOS clients are
# on JOG_IMAGING_IP/prefix; localhost is kept for jog-doctor and testing.
ALLOW_NET=""
if [[ -f "$ENV_FILE" ]]; then
  ALLOW_NET="$(sed -n 's/^JOG_AUTOJOIN_ALLOW_NET=//p' "$ENV_FILE" | tail -1)"
fi
if [[ -z "$ALLOW_NET" ]]; then
  ALLOW_NET="$(awk -F= '/^JOG_IMAGING_IP=/{ip=$2} /^JOG_IMAGING_PREFIX=/{p=$2} END{if(p=="")p=24; if(ip!=""){split(ip,a,"."); print a[1]"."a[2]"."a[3]".0/"p}else print "10.99.0.0/24"}' "$ENV_FILE" 2>/dev/null || true)"
fi
[[ -n "$ALLOW_NET" ]] || ALLOW_NET="10.99.0.0/24"
printf '# Generated by jog-autojoin-setup.sh — comma-separated CIDRs.\nJOG_AUTOJOIN_ALLOW_NET=%s\n' "$ALLOW_NET" >"$AUTOJOIN_ENV"
chmod 0644 "$AUTOJOIN_ENV"
log "wrote $AUTOJOIN_ENV (JOG_AUTOJOIN_ALLOW_NET=$ALLOW_NET)"

log "installed $TARGET"
check || warn "post-install check found issues"
