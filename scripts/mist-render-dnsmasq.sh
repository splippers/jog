#!/bin/bash
set -euo pipefail
exec 2>>/tmp/mist_error.log

ERROR_LOG="/tmp/mist_error.log"
log() { echo "MIST-DNSMASQ: $*"; }
err() { echo "MIST-DNSMASQ-ERROR: $*" | tee -a "$ERROR_LOG" >&2; }

JOG_ENV="${MIST_ENV:-${MIST_ENV:-${JOG_ENV:-/etc/mist/mist.env}}}"
if [[ ! -f "$JOG_ENV" ]]; then
  err "Missing $JOG_ENV (copy from MIST/config/mist.env.example)"
  exit 1
fi
# shellcheck disable=SC1090
source "$JOG_ENV"

: "${JOG_USB_IFACE:?Set JOG_USB_IFACE in $JOG_ENV}"
: "${JOG_DHCP_START:?}"
: "${JOG_DHCP_END:?}"
: "${JOG_DHCP_NETMASK:?}"
: "${JOG_DHCP_LEASE_HOURS:?}"
: "${JOG_NEXT_SERVER:?}"
: "${JOG_DHCP_ROUTER:?}"

OUT="${1:-/etc/dnsmasq.d/99-mist-imaging.conf}"
mkdir -p "$(dirname "$OUT")"

GUARD="${MIST_DHCP_GUARD:-${MIST_DHCP_GUARD:-${JOG_DHCP_GUARD:-/usr/local/bin/mist-dhcp-guard.py}}}"
IFACE="$JOG_USB_IFACE"
DHCP_IFACE="$IFACE"
if [[ -e "/sys/class/net/$IFACE/brport/bridge" ]]; then
  DHCP_IFACE=$(basename "$(readlink -f "/sys/class/net/$IFACE/brport/bridge" 2>/dev/null || true)")
  [[ -n "$DHCP_IFACE" && "$DHCP_IFACE" != "." && "$DHCP_IFACE" != "/" ]] || DHCP_IFACE="$IFACE"
fi
mapfile -t ALL_IFACES < <(python3 -c 'import os; print("\n".join(sorted(os.listdir("/sys/class/net"))))' 2>/dev/null || true)

write_disabled() {
  {
    echo "# Generated by mist-render-dnsmasq.sh — do not edit by hand."
    echo "# DHCP disabled: $1"
    echo "port=0"
    echo "bind-interfaces"
    echo "except-interface=lo"
    for other in "${ALL_IFACES[@]}"; do
      [[ "$other" == "lo" ]] && continue
      echo "no-dhcp-interface=$other"
    done
  } >"$OUT"
  log "DHCP disabled on all interfaces: $1"
}

if [[ ! -x "$GUARD" ]]; then
  write_disabled "safety guard missing at $GUARD"
  exit 0
fi
if ! "$GUARD" validate "$IFACE" >/dev/null; then
  write_disabled "$IFACE is not a USB Ethernet interface"
  exit 0
fi
if ! PROBE_OUTPUT="$("$GUARD" check "$IFACE" "${JOG_IMAGING_IP:-}" 2>&1)"; then
  write_disabled "DHCP traffic check failed on $IFACE: ${PROBE_OUTPUT//$'\n'/ }"
  exit 0
fi
log "DHCP probe: ${PROBE_OUTPUT//$'\n'/ }"

{
  echo "# Generated by mist-render-dnsmasq.sh — do not edit by hand."
  echo "# USB Ethernet imaging NIC only; DHCP is disabled on every other interface."
  echo "interface=$DHCP_IFACE"
  echo "bind-dynamic"
  echo "except-interface=lo"
  for other in "${ALL_IFACES[@]}"; do
    [[ "$other" == "lo" || "$other" == "$IFACE" || "$other" == "$DHCP_IFACE" ]] && continue
    echo "no-dhcp-interface=$other"
  done
  echo
  echo "log-dhcp"
  echo "log-facility=/var/log/dnsmasq-imaging.log"
  echo "dhcp-range=${JOG_DHCP_START},${JOG_DHCP_END},${JOG_DHCP_NETMASK},${JOG_DHCP_LEASE_HOURS}h"
  echo "dhcp-option=option:router,${JOG_DHCP_ROUTER}"
  echo "dhcp-option=option:dns-server,${JOG_NEXT_SERVER}"
  UPSTREAM_DNS="${JOG_UPSTREAM_DNS:-}"
  if [[ -z "$UPSTREAM_DNS" ]]; then
    UPSTREAM_DNS=$(python3 - "${MIST_BACKHAUL_IFACE:-${MIST_BACKHAUL_IFACE:-${JOG_BACKHAUL_IFACE:-wlp0s20f3}}}" <<'PYDNS'
import subprocess, sys
try:
    out = subprocess.run(["resolvectl", "dns", sys.argv[1]], capture_output=True, text=True, timeout=3).stdout
except Exception:
    out = ""
for part in out.split(":", 1)[-1].split():
    if part.count(":") <= 1 and not part.startswith(("10.", "127.", "fe80::")):
        print(part)
PYDNS
)
  fi
  [[ -n "$UPSTREAM_DNS" ]] || UPSTREAM_DNS="1.1.1.1 8.8.8.8"
  for dns_server in $UPSTREAM_DNS; do
    echo "server=$dns_server"
  done
  echo
  echo "dhcp-option=option:tftp-server,${JOG_NEXT_SERVER}"
  BOOTFILE="${MIST_DHCP_BOOTFILE:-${MIST_DHCP_BOOTFILE:-${JOG_DHCP_BOOTFILE:-ubuntu-signed/shimx64.efi}}}"
  BOOTSIZE=$(stat -c %s "/tftpboot/$BOOTFILE" 2>/dev/null || echo 0)
  BOOTBLOCKS=$(( (BOOTSIZE + 511) / 512 ))
  echo "dhcp-option=13,$BOOTBLOCKS"
  echo "dhcp-boot=$BOOTFILE,,${JOG_NEXT_SERVER}"
  echo "dhcp-vendorclass=set:mist-bios,PXEClient:Arch:00000"
  echo "dhcp-vendorclass=set:mist-uefi-x64,PXEClient:Arch:00007"
  echo "dhcp-boot=tag:mist-bios,ipxe.pxe,,${JOG_NEXT_SERVER}"
  echo "dhcp-boot=tag:mist-uefi-x64,$BOOTFILE,,${JOG_NEXT_SERVER}"
} >"$OUT"

log "Wrote $OUT (interface=$DHCP_IFACE, USB source=$IFACE, USB DHCP probe clear)"
