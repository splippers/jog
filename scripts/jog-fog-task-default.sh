#!/bin/bash
set -euo pipefail
umask 027

JOG_ENV="${JOG_ENV:-${JOG_ENV:-${JOG_ENV:-/etc/jog/jog.env}}}"
FOG_ENV="${FOG_ENV:-/etc/jog/fog-api.env}"
TFTP="${JOG_TFTP_ROOT:-${JOG_TFTP_ROOT:-${JOG_TFTP_ROOT:-/tftpboot}}}"
OUT="$TFTP/grub/default.cfg"
MARKER=/run/jog-fog-task-active

[[ -r "$JOG_ENV" && -r "$FOG_ENV" ]] || exit 0
set +x
set -a
. "$JOG_ENV"
. "$FOG_ENV"
set +a

HOST_ID="${JOG_FOG_HOST_ID:-${JOG_FOG_HOST_ID:-${JOG_FOG_HOST_ID:-1}}}"
HOST_IDS="${JOG_FOG_HOST_IDS:-${JOG_FOG_HOST_IDS:-${JOG_FOG_HOST_IDS:-$HOST_ID}}}"
BASE="${JOG_FOG_API_URL:-}"
API="${FOG_API_TOKEN:-}"
USER="${FOG_USER_TOKEN:-}"
[[ "$HOST_ID" =~ ^[0-9]+$ && -n "$BASE" && -n "$API" && -n "$USER" ]] || exit 0
mkdir -p "$(dirname "$OUT")"
TMP="$(mktemp "${OUT}.XXXXXX")"
trap 'rm -f "$TMP"' EXIT

PAYLOAD="$(curl -fsS --max-time 6 "${BASE%/}/task/active" \
  -H "fog-api-token: $API" -H "fog-user-token: $USER" -H 'Accept: application/json')" || exit 0
ACTIVE_HOSTS="$(printf '%s' "$PAYLOAD" | python3 -c '
import json
import sys

try:
    data = json.load(sys.stdin)
except (ValueError, TypeError):
    sys.exit(2)
rows = data.get("data", []) if isinstance(data, dict) else data
if not isinstance(rows, list):
    sys.exit(2)
hosts = {item.strip() for item in sys.argv[1].split(",") if item.strip()}
active = sorted({
    str(r.get("hostID"))
    for r in rows
    if isinstance(r, dict)
    and str(r.get("hostID")) in hosts
    and int(r.get("stateID") or 0) in (1, 2, 3)
}, key=int)
print(",".join(active))
' "$HOST_IDS")" || exit 0
ACTIVE=0
[[ -n "$ACTIVE_HOSTS" ]] && ACTIVE=1

PREV=""
[[ -r "$MARKER" ]] && PREV="$(tr -d '[:space:]' < "$MARKER")"

vm_for_mac() {
  local want="${1,,}" domain mac
  [[ -n "$want" ]] || return 1
  while IFS= read -r domain; do
    [[ -n "$domain" ]] || continue
    while IFS= read -r mac; do
      if [[ "${mac,,}" == "$want" ]]; then
        printf '%s' "$domain"
        return 0
      fi
    done < <(virsh dumpxml --domain "$domain" 2>/dev/null | python3 -c '
import re
import sys
for item in re.findall(r"<mac\s+address=[\"\x27]([^\"\x27]+)[\"\x27]", sys.stdin.read(), re.I):
    print(item)
')
  done < <(virsh list --all --name 2>/dev/null || true)
  return 1
}

if [[ "$ACTIVE" == "1" ]]; then
  printf '# Generated by jog-fog-task-default.sh — active task for FOG host(s) %s\nset default=1\n' "$ACTIVE_HOSTS" >"$TMP"
  DEVICE=network
else
  printf '# Generated by jog-fog-task-default.sh — no active task for FOG host(s) %s\nset default=0\n' "$HOST_IDS" >"$TMP"
  DEVICE=hd
fi

TARGET_IDS="$ACTIVE_HOSTS"
if [[ -z "$TARGET_IDS" && -n "$PREV" && "$PREV" != "0" ]]; then
  TARGET_IDS="$PREV"
fi

if [[ -n "$TARGET_IDS" && "$TARGET_IDS" != "$PREV" ]]; then
  IFS=',' read -ra ACTIVE_IDS <<<"$TARGET_IDS"
  for ID in "${ACTIVE_IDS[@]}"; do
    WAKE_VM=""
    MAC=""
    read -r MAC _ <<<"$(mysql -N fog -e "SELECT hmMAC FROM hostMAC WHERE hmHostID=$ID AND hmPrimary=1 LIMIT 1" 2>/dev/null || true)"
    if [[ -n "$MAC" ]]; then
      FOUND="$(vm_for_mac "$MAC")" || FOUND=""
      [[ -n "$FOUND" ]] && WAKE_VM="$FOUND"
    fi
    if [[ -z "$WAKE_VM" && "$ID" == "$HOST_ID" && -n "${JOG_IMAGING_VM:-}" ]]; then
      WAKE_VM="$JOG_IMAGING_VM"
    fi
    [[ -z "$WAKE_VM" ]] && continue
    STATE="$(virsh domstate --domain "$WAKE_VM" 2>/dev/null || true)"
    if [[ -z "$STATE" || "${STATE,,}" == shut* || "${STATE,,}" == stopped* ]]; then
      /usr/local/sbin/jog-portal-network.sh vm boot "$WAKE_VM" "$DEVICE" 1 >/dev/null 2>&1 || true
    fi
  done
fi
printf '%s\n' "${ACTIVE_HOSTS:-0}" >"$MARKER"
chmod 0644 "$TMP"
mv -f "$TMP" "$OUT"
trap - EXIT
